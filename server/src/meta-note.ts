// 元叙述（正文里的"自查备注"）—— QC-42 的判据。
//
// 现象（r158 帖3 随安SuiAan 原文）：
//   「…话不该说死。 /  / (注：此回复严格遵循指令——驳前句（她催的动机），给后见（你在乎她），
//     长度约 38 字，无废话，无禁止词，无空行。)」
// 模型没在回帖，它在**交作业**：把"我在按指令写"这件事写进了正文。用户看得见脏东西。
//
// 来源已经查清（我 + qc 各自独立跑，结论一致）：**不是 prompt 字面串被念出来**。
// 16 位 × 6 帖 × 2 种 `said` = 192 条最终 prompt 里，下面这些串逐字命中 **0 次**。
// 真正的产地是 16 位**共享**的规则区那几行的"自检口令"（`personas.ts:934/1033/1036/1050`）：
//   934  `上限 ${p.maxChars} 字`     → "长度约 38 字"
//   1033 `那它就是废话，删掉`        → "无废话"
//   1036 `不要空行分段`             → "无空行"
//   1050 `不换行、不空行、不用"/"分隔…不加"回复：""@某某"之类的标记` → "无禁止词" + `(注：…)`
// 模型把**禁令翻成"无X"的自述**，再配上"检验报告"的口吻交回来。
//
// 所以判据只能**窄**：只认元层自述的固定说法。一条会误报的规则比没有规则更坏 ——
// 「我注了下水」「备注写在这儿」这类正常句子必须穿过（`注` 单独出现不算，只有前面贴着括号
// 且后面跟着冒号的 `(注：` / `（注：` 才算）。
//
// 口径由 Lead m05059 定死：**就用查出来的这几个串，不许扩大词表**。
// 消费者：`eval.ts`（命中即判失败，b1）；`replies.ts` 的守门（命中一次重说、再命中就丢弃，b2）。
const META_NOTE_SOURCE = String.raw`[（(]注[:：]|严格遵循|长度约\s*\d+\s*字|无废话|无禁止词|无空行`;

/** 命中即"正文里在自述它是被指令写出来的"。单测用（非全局，可反复 `test`）。 */
export const META_NOTE = new RegExp(META_NOTE_SOURCE);

/** 一条回复里所有命中的元叙述串（去重，保序）。 */
export function metaNotes(text: string): string[] {
  const all = text.matchAll(new RegExp(META_NOTE_SOURCE, 'g'));
  return [...new Set([...all].map((m) => m[0]))];
}
