    // 不是跟人一对一聊天：两条硬边界（不 @ 人、不写"我同意/说得对"）就写在同一块里。
    // `said` 为空（帖子里他第一个说话，以及 smoke/eval 的全部调用）时**一个字都不加** ——
    // 第一版那 24 条已经稳在"一句短话"上，没理由让最先说话的人先读一段新规矩。
    // 引文用"名字：话"接在**一行**里（不排成每行一条）—— 教训见下文拍平实验那一段：
    // **模型会模仿 prompt 的排版**，排成清单它就回成清单。
