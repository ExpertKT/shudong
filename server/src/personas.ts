/**
 * 人设 = 这个项目的命门，别当配置文件随便改。
 *
 * ── 写人设的铁律 ─────────────────────────────────────────────────────────────
 *
 * 1. **写"他是谁、他的一天怎么过"，不要写"他的标签"。** 标签会被模型表演 ——
 *    你写"嘴毒但在帮忙"，它就每条都先怼一句。
 *
 * 2. **tagline 只给界面看，绝不进 prompt。** 它是列表上那行小字，不是他的自我认知。
 *    拼进去 = 让他演标签。
 *
 * 3. **life 里只写"条件"，不写"可以当素材讲的具体往事"。**
 *    往事全部放进 `memories`，由 `pickMemory()` 一次只放一条进去（或者一条都不放）。
 *    为什么必须这样分工，见下面这条 —— 这是被两轮返工打出来的结论：
 *
 *    > 模型没有持久状态。arXiv:2510.24831 说得很直白：它"每次推理都要从零重建我是谁"。
 *    > 所以它一定会抓住 prompt 里**最具体的那条细节**当身份锚点，然后每条回帖都用它。
 *    >
 *    > 这个项目已经亲历两次：第一版把"关东煮"写进人设（用户原话："0 人在意你关东煮"）；
 *    > 删掉之后，"绿萝"顶上来（6/6 条都提）；删掉绿萝，"上学期旁听文学课坐最后一排"
 *    > 又顶上来（5/6 条都提）。**删一个锚点只会把下一个顶上来**，改文本治不了。
 *    >
 *    > 治得了的是：prompt 里根本不存在"一条特别具体的往事"这种东西，
 *    > 讲不讲、讲哪一条，由外面按次数分配（`pickMemory`）。模型没有状态，
 *    > 那就由有状态的一方来分配 —— 这也是以后"记得你"要用的同一套机制。
 *
 * 4. **别把人设写得太"好用"。** 凡自带一个现成比喻或人生态度的细节
 *    （"绿萝你以为会死结果活得挺好"），模型会当万能钥匙套到每个帖子上。
 *
 * ── 篇幅和人味的数字口径 ─────────────────────────────────────────────────────
 * **数字不在这个文件里** —— 唯一来源是 `eval.ts` 的 `BASELINE`（那里标了「暂借·未核」，
 * 等 task-12 拿到当下真人语料后重算）。这里只记那批样本的来源：豆瓣树洞/情感帖 60 条真人回复。
 * 它们说的事是：第一版条条 100 字、条条给建议、条条以问句收尾 —— 那正是"AI 味"本身。
 * （lead 2026-10：基线口径原来在三个地方漂移 —— 这里写"11~30"、`eval.ts` 写 median 30、
 *  报告里说过"约 20"。三处并存的话，下次谁都说不清改了没改，所以只留 `eval.ts` 一处。）
 */
/**
 * 一条往事，外加"什么时候讲得出来"。
 *
 * `when` 是**选的时候用的钥匙，绝不进 prompt** —— 进去就又变成锚点了（见文件头第 3 条）。
 * 它治的是这个病：往事原来只按帖子 id 轮换，于是同一件事在**固定的那几帖**上反复出现
 * （阿禾在橘猫那帖端了五轮"美甲店学不下去"）。往事得由帖子的话题决定讲不讲。
 */
export type Memory = {
  /** 往事本身，≤21 字（理由见阿禾那段注释） */
  text: string;
  /** 帖子正文里只要出现这里任意一个词，这条往事才**允许**被讲 */
  when: string[];
};

/**
 * 他多久路过一次树洞 —— 排期参数，**不是他的性格**，所以绝不拼进 `systemPrompt`。
 * 回帖是贴吧式的异步楼层：前端每隔几秒叫一次 `POST /api/feed/tick`，每次最多让一位到点的吧友说话，
 * 到点间隔按档位抽（surfer 5 秒~25 秒 / evening 1.5 分~15 分 / slow 30 分~2 小时）。
 * 第 0 位（`sort` 最小的阿禾）固定按 surfer 走，保证用户发帖后半分钟内一定有人吭声。
 */
export type Pace = 'surfer' | 'evening' | 'slow';

export type Persona = {
  slug: string;
  name: string;
  /** 只给界面看的一行小字。**绝不拼进 prompt**（拼了就是"演标签"） */
  tagline: string;
  accent: string;
  sort: number;

  /** 他多久路过一次（见 `Pace`）。**排期参数，绝不拼进 prompt** */
  pace: Pace;

  /** 他是谁：哪来的、一天怎么过、跟谁住、最近在为什么费劲。**只写条件，不写往事** */
  life: string;
  /** 他怎么说话：句子长短、标点习惯、口头语，以及**他不说哪些话**；讲不讲自己写这儿 */
  voice: string;
  /** 他关心什么、会追问什么、会对什么事有反应 —— 不是他会怎么讲自己 */
  cares: string;

  /**
   * 他**自己会主动接**的话茬词（每人 4~8 个），是 `cares` 的**机器可读版**。
   *
   * 唯一用途：服务端那个"这一帖他到底要不要接话"的抽签函数 —— 有意思的帖人多、没意思的帖人少
   * （用户的验收话："每个吧友根据自身性格判断要不要接这个话茬"）。所以它**绝不进 prompt**
   * （不进 `personaText`、不进 `systemPrompt`，`systemPrompt` 里根本没有读它的代码路径）：
   * 一旦进去，它就变成新的身份锚点 —— 见文件头第 3 条，我们前面那几轮白做。
   *
   * 挑词的标准只有一条：**要有区分度**。写"累""难受""烦"这种人人都接的词等于没写，
   * 而且会把冷帖也弄成热帖；反过来，泛词也会让某个人对什么都命中（`when` 的 '空'/'半夜'/'妈'
   * 三次返工都是这个病，见那几条注释）。所以词要么指一件具体的事（'催婚'），
   * 要么指一种具体的处境（'一个人在外地'）—— 不指情绪。
   */
  topics: string[];

  /**
   * 他能讲的**具体往事**，一条一条的。每次回帖最多放一条进 prompt（见 `pickMemory`），
   * 而且要帖子正文里出现了这条的 `when` 词才放。
   */
  memories: Memory[];

  /**
   * 他讲不讲自己。**"有生活"和"爱讲自己"是两件事** —— 这个字段就是这两件事的分界。
   * `false` = 他有一肚子往事，但从不端出来（老陆、起司）；`pickMemory` 直接返回 null。
   *
   * 为什么要有它：我一开始用 `memories: []` 表示"不讲自己"，那等于"他没有生活"，
   * 而那正是用户投诉的原话「这些agent没有自己的人生轨迹，没有对应的生活体验」。
   * 补上往事后又走到另一头：模型把往事**原样端出来**（迭代 10 老陆帖4 "有个换电池的
   * 老主顾，来了三十年"，起司帖2 "我也刚搬过那晚外卖没吃完"），两个最不爱讲自己的人
   * 反倒成了全轮最倒苦水的两个，聚合自曝率从 21% 冲到 38%。
   * 所以：**往事是生活，`tells` 才是性格。** 别再用空数组去表达性格。
   */
  tells: boolean;

  /**
   * 他的"招牌道具"。**只给 eval.ts 用**，绝不拼进 prompt。
   * 理由见文件头第 3 条：写进 prompt 就等于要求他反复提。
   */
  props: string[];
  /** 篇幅上限（字）。**唯一口径** —— prompt 和 eval 都读它，别在 life 里再写一遍 */
  maxChars: number;

  /** 每秒大概打几个字，用来控制流式节奏 */
  cps: number;
  /** 看到帖子到开始打字之间的停顿（毫秒） */
  thinkMs: number;
  maxTokens: number;
};

/** 拼成一段"他是谁"，prompt 和落库都读这一个。**注意它不含 memories。** */
export function personaText(p: Persona): string {
  return [p.life, p.voice, p.cares].join('\n');
}

/**
 * 这次回帖要不要让他讲一件自己的事？讲哪一件？
 *
 * **为什么现在要看得见帖子正文**：原来看不见，只按帖子 id 轮换，于是同一件事会在
 * **固定的那几帖**上反复出现 —— 阿禾在"橘猫蹲在电动车底下"那帖端了五轮
 * "美甲店学不下去，手机一放就干坐着"（迭代 15/16/18/19/22）。那不是采样噪声：
 * 帖 id 是固定的，所以每一轮都必然抽到它。那是"为了凸显人设而凸显人设"的机器版本，
 * 也正是用户第一次投诉的那个病 —— 所以往事必须**由帖子的话题决定讲不讲**。
 *
 * 规则（Lead 定的契约）：`when` 里有词出现在帖子正文里才允许讲；一条都对不上就返回
 * null（这次不讲自己）；多条都对上，按 `postId` 挑一条（保留"不总是讲同一件"）。
 *
 * 于是**自曝率跟着帖子走**，不再是一个要被追平的目标数字 —— 真人基线 28% 是平均，
 * 不是配额（有生活 ≠ 爱讲自己，见 `tells`）。
 *
 * **第 4 个参数 `said`（Lead 的 task-19，2026-10）**：同一帖里**这个人自己**前面楼层已经
 * 说出口的话。加它的原因不是"随机性不够"——`pickMemory` 对同一帖是**确定性**的（同一个
 * postId + 同一段正文 ⇒ 永远返回同一条往事），所以一个帖子里他第二次、第三次开口，
 * 讲的一定是同一件事。qc 的 QC-22 在真库那条线上抓到的就是这个：
 * anhe 在 2/5/7/9 楼"四版同一件往事"。旧行为（不传 `said`）原样保留：
 * 不传 = 不过滤，向后兼容，`index.ts` 的调用点可以后跟（bond）。
 */
export function pickMemory(
  p: Persona,
  postId: number,
  postText: string,
  /** 同一帖里他自己前面楼层已经说出口的文本。说过的那条往事不再讲第二遍。 */
  said: string[] = [],
  /**
   * **讲过的往事号**（task-66/67，2026-10）：这个人**这一辈子**已经讲过的往事在
   * `p.memories` 里的下标，由 `index.ts` 从 `memories_told` 表读出来传进来。
   *
   * 为什么不能靠比对文字：模型是**改写**着讲的，逐字子串永远认不出来。task-64 试过
   * 只把撞 `topics` 的 `when` 词撤掉，结果是候选集直接变空、人设被弄哑（阿禾可讲楼层
   * 10/36 → 3/36）。按**身份**记账才断得干净，`when` 的词也就能放回来。
   *
   * `told` 可省 ⇒ 别的调用点（`eval.ts`、`relations.ts`、测试）不受影响。
   */
  told: number[] = [],
): string | null {
  // 运行时兜底：`index.ts` / `relations.ts` 的调用点还没跟着改（那两个文件不在我的写作用域里），
  // 它们跑到这里时 `postText` 是 undefined —— 这时候**这次就不讲自己**，而不是让线上回帖抛异常。
  // tsc 那边仍然因为"少传一个参数"报错（签名就是要三个），所以这个兜底只防崩，不掩盖该改的调用点。
  if (!postText) return null;
  if (!p.memories.length) return null;
  // 有往事 ≠ 爱讲往事。老陆和起司的往事只在他们心里，从不端出来（见 `tells`）。
  if (!p.tells) return null;
  const cand = p.memories.filter((m) => m.when.some((w) => postText.includes(w)));
  // 对不上就闭嘴 —— 硬接上去比不提更假（人家说猫，她接一句"我也学过美甲"）
  if (!cand.length) return null;
  // 候选多于一条时轮转，不要固定取某一条。
  // Lead 2026-10 的修：**撞同一件往事通常不是取法的问题，是候选集缩成了 1 条**
  // （阿禾的"擦桌子哭"原来带泛词 '半夜'，帖1 和帖6 都只命中它 → 轮转公式救不了，
  // 得把泛词撤掉、让每条往事的 `when` 有区分度）。这一句只在候选 >1 时才起作用，
  // 留着是为了"同一人多条往事都对上时别每次都讲第一件"。
  //
  // 讲过的先剔掉。两道闸门，各管各的：
  //   - `told`（task-66/67）：按**身份**。这个人这辈子讲过这条往事就不再讲 —— 模型改写
  //     过多少遍都认得出来，因为它认的是下标，不是字。
  //   - `said`（task-19）：同一帖里他自己前半句刚把原文引出来过。字面那道。
  // 剔完没有别的可讲就返回 null：**这一层他不讲自己**，比硬换一件不相干的事更真。
  const known = told.length ? cand.filter((m) => !told.includes(p.memories.indexOf(m))) : cand;
  const fresh = said.length ? known.filter((m) => !said.some((t) => t.includes(m.text))) : known;
  if (!fresh.length) return null;
  return fresh[(postId >> 1) % fresh.length]?.text ?? null;
}

