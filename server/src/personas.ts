          // r127 教训：**`said` 里那一段引文就是新的弹药**。阿禾先说了「把手机扣过去，坐着也成。」，
          // 老陆的下半句直接接成「把手机扣过去坐着也成，不用看那些东西。」（撞词判据 + 他自己还吃到
